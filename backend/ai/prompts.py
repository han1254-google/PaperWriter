def get_discipline_guide(discipline: str | None) -> str:
    return DISCIPLINE_GUIDES.get(discipline or "", DISCIPLINE_GUIDES["法学"])


def get_style_guide(discipline: str | None) -> str:
    """正文写作风格要求（从学科指南中提取写作要求部分）。"""
    guide = get_discipline_guide(discipline)
    lines = [ln for ln in guide.splitlines() if "写作要求" in ln or "客观" in ln]
    if lines:
        return "\n".join(lines)
    return "- 学术写作风格，客观精确，避免文学化表达。"


def render_chunks(chunks: list[dict[str, Any]], *, max_chars: int | None = None) -> str:
    """把片段列表渲染为模型上下文材料。

    chunks: {id, title, authors, publisher, published_at, doc_type,
             chunk_type, heading_path, page_start, page_end, text}
    """
    lines: list[str] = []
    total = 0
    for i, c in enumerate(chunks, 1):
        cid = c.get("id", c.get("chunk_id"))
        head = f"[材料 {i} · 片段ID {cid}]《{c.get('title') or '未命名文档'}》"
        meta_bits = []
        if c.get("authors"):
            meta_bits.append(f"作者：{c['authors']}")
        if c.get("publisher"):
            meta_bits.append(f"出处：{c['publisher']}")
        if c.get("published_at"):
            meta_bits.append(f"时间：{c['published_at']}")
        if c.get("doc_type"):
            meta_bits.append(f"类型：{c['doc_type']}")
        if c.get("heading_path"):
            meta_bits.append(f"位置：{c['heading_path']}")
        if c.get("page_start"):
            pages = f"第{c['page_start']}页" + (f"-{c['page_end']}页" if c.get("page_end") and c["page_end"] != c["page_start"] else "页")
            meta_bits.append(pages)
        block = head + ("\n" + "；".join(meta_bits) if meta_bits else "") + "\n" + (c.get("text") or "").strip()
        total += len(block)
        if max_chars and total > max_chars:
            break
        lines.append(block)
    return "\n\n".join(lines)


